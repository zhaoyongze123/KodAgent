async function writeDocx(directory, filename, title, sections) {
  const children = [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 360 }, children: [
      new TextRun({ text: title, bold: true, font: "SimSun", size: 36 }),
    ] }),
  ];
  for (const section of sections) {
    children.push(new Paragraph({ heading: HeadingLevel.HEADING_1, children: [
      new TextRun({ text: section.heading, font: "SimSun" }),
    ] }));
    for (const text of section.paragraphs) {
      children.push(new Paragraph({ spacing: { after: 140, line: 360 }, children: [
        new TextRun({ text, font: "SimSun", size: 22 }),
      ] }));
    }
  }
  const document = new Document({
    styles: {
      default: { document: { run: { font: "SimSun", size: 22 } } },
    },
    sections: [{
      properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 } } },
      children,
    }],
  });
  fs.writeFileSync(path.join(directory, filename), await Packer.toBuffer(document));
}

