HEADER_FILL = PatternFill("solid", fgColor="1F4E78")
SUBHEADER_FILL = PatternFill("solid", fgColor="D9EAF7")


def style_sheet(sheet, widths: list[int]) -> None:
    sheet.freeze_panes = "A2"
    sheet.sheet_view.showGridLines = False
    for index, width in enumerate(widths, start=1):
        sheet.column_dimensions[get_column_letter(index)].width = width
    for cell in sheet[1]:
        cell.font = Font(name="Microsoft YaHei", bold=True, color="FFFFFF")
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    for row in sheet.iter_rows(min_row=2):
        for cell in row:
            cell.font = Font(name="Microsoft YaHei", size=10)
            cell.alignment = Alignment(vertical="top", wrap_text=True)
    sheet.row_dimensions[1].height = 30


def create_workbook(path: Path, sheets: list[tuple[str, list[str], list[list[object]], list[int]]]) -> None:
    workbook = Workbook()
    first = True
    for title, headers, rows, widths in sheets:
        sheet = workbook.active if first else workbook.create_sheet()
        first = False
        sheet.title = title
        sheet.append(headers)
        for row in rows:
            sheet.append(row)
        style_sheet(sheet, widths)
        for row_index in range(2, sheet.max_row + 1):
            sheet.row_dimensions[row_index].height = 34
    workbook.save(path)


