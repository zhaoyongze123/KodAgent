import fs from 'node:fs/promises';
import { FileBlob, SpreadsheetFile } from '@oai/artifact-tool';
const input = '/Users/mac/项目/若伊部署/output/xlsx/规划院部门树人员与审批流程-20260710.xlsx';
const output = '/Users/mac/项目/若伊部署/tmp/sheets/department_summary_preview.png';
const wb = await SpreadsheetFile.importXlsx(await FileBlob.load(input));
const sheet = wb.worksheets.getItem('部门统计');
const preview = await wb.render({ sheetName: sheet.name, autoCrop: 'all', scale: 1, format: 'png' });
await fs.writeFile(output, new Uint8Array(await preview.arrayBuffer()));
console.log(output);
