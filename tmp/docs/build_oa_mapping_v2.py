def read_source_rows():
    with SOURCE_CSV.open(encoding='utf-8-sig', newline='') as f:
        rows = list(csv.reader(f))
    result = []
    for row in rows[1:]:
        result.append({'id': row[0], 'account': row[1], 'role': row[2], 'name': row[1].split('/')[0]})
    return result


def build_record(rec):
    name = rec['name']
    if name in {'系统管理员', '751i扫描用户', 'demo', '测试用户2'}:
        return ['无规划院业务归属', '非OA业务账号', '不纳入规划院OA审批主流程', 0, '不作为规划院OA流程发起人；如需验证登录或权限，单独测试', '新版组织架构表中没有该账号对应的规划院业务部门。']
    if name not in ORG_BY_NAME:
        return ['待核实', '未匹配到新版组织架构', '无法从新版组织架构表确定审批链', 0, '先补齐组织归属，再进行OA流程测试', '证据不足：新版组织架构表中未找到该用户。']
    dept, org_role = ORG_BY_NAME[name]
    if name == '侯斌超':
        return [dept, '院长/审批终点账号', '审批终点账号，不作为普通发起人', 0, '保留账号，作为院长审批节点', org_role]
    if name == '朱新捷':
        return [dept, '总规划师/技术审查特殊账号', '侯斌超（院长）', 1, '保留账号，作为审批节点登录后人工审批', '新版组织架构表将朱新捷归入技术审查室；架构图标注其可直接到院长。']
    if name == '严己':
        return [dept, '技术审查特殊流程', '张华、张龄、朱新捷三选一 → 侯斌超（院长）', 2, '流程完成后可删除发起人再创建下一名用户；三选一节点账号保留', '架构图标注“严己自己点选”，需验证页面显示具体人名。']
    if name == '赖志勇':
        return [dept, '技术审查特殊流程', '朱新捷（总规划师） → 侯斌超（院长）', 2, '流程完成后可删除发起人再创建下一名用户；审批节点账号保留', '新版组织架构表将赖志勇归入技术审查室；架构图标注“赖志勇到朱新捷”。']
    if dept in ROUTES:
        flow_type, approvers, evidence = ROUTES[dept]
        if name in {'马倩', '邴燕萍'}:
            return [dept, f'{org_role}', approvers, approvers.count('→') + 1, '保留账号，既作为组织负责人也可能作为审批节点', evidence + ' 该人员同时承担分管领导职责。']
        return [dept, f'{org_role}', approvers, approvers.count('→') + 1, '流程完成且无报错后可删除本次发起人，再创建下一名用户；审批节点账号保留', evidence]
    return [dept, org_role, '待补充该部门审批链', 0, '先补齐审批链配置，再开始测试', '新版组织架构表已确认部门归属，但当前材料未给出完整审批链。']


def main():
    headers = ['序号', '可道云用户', '可道云角色', '新版唯一所属所/部门', '新版组织角色', '测试分类', '审批经过人员（不含发起人）', '审批节点数', '账号处理建议', '依据/备注']
    rows = []
    for rec in read_source_rows():
        dept, org_role, approvers, node_count, action, note = build_record(rec)
        flow_type = '非OA业务账号' if dept == '无规划院业务归属' else ('待核实' if dept == '待核实' else ('特殊流程' if '特殊' in org_role or '技术审查' in org_role else ('院部账号' if dept == '院部' else '标准流程')))
        rows.append([rec['id'], rec['name'], rec['role'], dept, org_role, flow_type, approvers, node_count, action, note])
    with OUT.open('w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(headers)
        writer.writerows(rows)
    print(OUT)
    print('data_rows=', len(rows))
    print('unmatched=', [r[1] for r in rows if r[3] == '待核实'])


if __name__ == '__main__':
    main()
